import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:share_plus/share_plus.dart';

import '../models/project_brief.dart';
import '../services/jump_runway_cad_generator.dart';
import 'automatic_floor_plan_screen.dart';

class JumpRunwayCadScreen extends StatefulWidget {
  const JumpRunwayCadScreen({super.key, required this.name, required this.brief, required this.widthFt, required this.depthFt});
  final String name;
  final ProjectBrief brief;
  final double widthFt, depthFt;

  @override
  State<JumpRunwayCadScreen> createState() => _JumpRunwayCadScreenState();
}

class _JumpRunwayCadScreenState extends State<JumpRunwayCadScreen> {
  late final _result = JumpRunwayCadGenerator().generate(widget.brief, widthFt: widget.widthFt, depthFt: widget.depthFt);
  bool _sharing = false;

  Future<void> _share(BuildContext context, String data, String extension, String mime) async {
    if (_sharing) return;
    final box = context.findRenderObject();
    final origin = box is RenderBox ? box.localToGlobal(Offset.zero) & box.size : null;
    final name = widget.name.trim().replaceAll(RegExp(r'[^a-zA-Z0-9_-]+'), '_');
    setState(() => _sharing = true);
    try {
      await Share.shareXFiles([XFile.fromData(Uint8List.fromList(utf8.encode(data)), mimeType: mime)],
        fileNameOverrides: ['${name.isEmpty ? 'project' : name}_jump_runway.$extension'], sharePositionOrigin: origin);
    } catch (_) {
      if (mounted) ScaffoldMessenger.of(this.context).showSnackBar(SnackBar(content: Text('Could not share the ${extension.toUpperCase()}.')));
    } finally {
      if (mounted) setState(() => _sharing = false);
    }
  }

  String _m(num mm) => (mm / 1000).toStringAsFixed(3);

  @override
  Widget build(BuildContext context) {
    final drawing = _result.drawing;
    return Scaffold(appBar: AppBar(title: const Text('Jump runway CAD')), body: SafeArea(child: ListView(
      padding: const EdgeInsets.all(16), children: [
        Text(widget.name, style: Theme.of(context).textTheme.headlineSmall),
        const SizedBox(height: 8),
        if (drawing == null) ...[
          const Text('No jump runway drawing generated'),
          const Text('Your brief was saved. Edit the dimensions to retry.'),
          if (_result.issue case final issue?) ListTile(leading: const Icon(Icons.info_outline), title: Text(issue)),
        ] else ...[
          Text('Full envelope ${_m(_result.widthMm)} × ${_m(_result.depthMm)} m'),
          for (final t in _result.takeoffs)
            Text('${t.event == 'long_jump' ? 'Long jump' : 'Triple jump'}: ${_m(t.approachMm)} m approach · ${_m(t.nearMm)}–${_m(t.farMm)} m from take-off line to sand edges'),
          const Text('Blue: runway · Orange: usable sand pit · Green: take-off lines · Grey: plot and reserve envelope.'),
          Builder(builder: (button) => Wrap(spacing: 10, children: [
            FilledButton.icon(icon: const Icon(Icons.ios_share), onPressed: _sharing ? null : () =>
              _share(button, drawing.toDxf(), 'dxf', 'application/dxf'), label: const Text('Share jump runway DXF')),
            OutlinedButton.icon(icon: const Icon(Icons.ios_share), onPressed: _sharing ? null : () =>
              _share(button, _result.toCsv()!, 'csv', 'text/csv'), label: const Text('Share take-off schedule CSV')),
          ])),
          CadPlanPreview(drawing: drawing),
          const Text('Horizontal geometry only. No runway gradients, board construction, sand depth, drainage, safety or competition approval.'),
        ],
      ],
    )));
  }
}
