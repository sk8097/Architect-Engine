import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:share_plus/share_plus.dart';

import '../models/project_brief.dart';
import '../services/raised_bed_cad_generator.dart';
import 'automatic_floor_plan_screen.dart';

class RaisedBedCadScreen extends StatefulWidget {
  const RaisedBedCadScreen({super.key, required this.name, required this.brief,
    required this.widthFt, required this.depthFt});
  final String name;
  final double widthFt, depthFt;
  final ProjectBrief brief;

  @override
  State<RaisedBedCadScreen> createState() => _RaisedBedCadScreenState();
}

class _RaisedBedCadScreenState extends State<RaisedBedCadScreen> {
  late final _result = RaisedBedCadGenerator().generate(widget.brief, widthFt: widget.widthFt, depthFt: widget.depthFt);
  bool _sharing = false;

  Future<void> _share(BuildContext context, String data, String extension, String mime) async {
    if (_sharing) return;
    final box = context.findRenderObject();
    final origin = box is RenderBox ? box.localToGlobal(Offset.zero) & box.size : null;
    final name = widget.name.trim().replaceAll(RegExp(r'[^a-zA-Z0-9_-]+'), '_');
    setState(() => _sharing = true);
    try {
      await Share.shareXFiles([XFile.fromData(Uint8List.fromList(utf8.encode(data)), mimeType: mime)],
        fileNameOverrides: ['${name.isEmpty ? 'project' : name}_raised_beds.$extension'], sharePositionOrigin: origin);
    } catch (_) {
      if (mounted) ScaffoldMessenger.of(this.context).showSnackBar(SnackBar(content: Text('Could not share the ${extension.toUpperCase()}.')));
    } finally {
      if (mounted) setState(() => _sharing = false);
    }
  }

  String _m(int mm) => (mm / 1000).toStringAsFixed(3);

  @override
  Widget build(BuildContext context) {
    final drawing = _result.drawing;
    return Scaffold(appBar: AppBar(title: const Text('Public garden raised-bed CAD')), body: SafeArea(child: ListView(
      padding: const EdgeInsets.all(16), children: [
        Text(widget.name, style: Theme.of(context).textTheme.headlineSmall),
        const SizedBox(height: 8),
        if (drawing == null) ...[
          const Text('No raised-bed drawing generated'),
          const Text('Your brief was saved. Edit the dimensions to retry.'),
          if (_result.issue case final issue?) ListTile(leading: const Icon(Icons.info_outline), title: Text(issue)),
        ] else ...[
          Text('${_result.beds.length} beds · Garden envelope ${_m(_result.envelopeWidthMm)} × ${_m(_result.envelopeDepthMm)} m'),
          Text('Clear growing area ${_result.growingAreaM2.toStringAsFixed(3)} m² · Net growing medium ${_result.mediumM3.toStringAsFixed(3)} m³'),
          Text('Internal path area ${_result.pathAreaM2.toStringAsFixed(3)} m²'),
          const Text('Green: path envelope · Orange: outside bed walls · Blue: clear growing interiors.'),
          Builder(builder: (button) => Wrap(spacing: 10, children: [
            FilledButton.icon(icon: const Icon(Icons.ios_share), onPressed: _sharing ? null : () =>
              _share(button, drawing.toDxf(), 'dxf', 'application/dxf'), label: const Text('Share raised-bed DXF')),
            OutlinedButton.icon(icon: const Icon(Icons.ios_share), onPressed: _sharing ? null : () =>
              _share(button, _result.toCsv()!, 'csv', 'text/csv'), label: const Text('Share bed takeoff CSV')),
          ])),
          CadPlanPreview(drawing: drawing),
          const Text('Concept only. Medium volume is net: no waste, compaction or settlement allowance. No wall design, irrigation, drainage or accessibility certification.'),
        ],
      ],
    )));
  }
}
