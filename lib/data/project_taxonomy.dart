// IDs below are stored in project briefs. Keep them stable when editing labels.
const projectTaxonomyVersion = 1;

class TaxonomyChoice {
  const TaxonomyChoice(this.id, this.label, {this.programId});
  final String id;
  final String label;
  final String? programId;
}

class TaxonomyGroup {
  const TaxonomyGroup(this.id, this.label, this.programId, this._types);
  final String id;
  final String label;
  final String programId;
  final List<TaxonomyChoice> _types;
  List<TaxonomyChoice> get types => List.unmodifiable([
    ..._types,
    const TaxonomyChoice('custom', 'Custom / unlisted type'),
  ]);
}

class TaxonomyCategory {
  const TaxonomyCategory(this.id, this.label, this.groups);
  final String id;
  final String label;
  final List<TaxonomyGroup> groups;
}

class TaxonomyProgram {
  const TaxonomyProgram(this.configurationLabel, this._configurations, this.spaces);
  final String configurationLabel;
  final List<TaxonomyChoice> _configurations;
  List<TaxonomyChoice> get configurations => List.unmodifiable([
    ..._configurations,
    const TaxonomyChoice('custom', 'Custom / unlisted configuration'),
  ]);
  final List<TaxonomyChoice> spaces;
}

T? taxonomyById<T>(Iterable<T> options, String? id, String Function(T) idOf) {
  for (final option in options) {
    if (idOf(option) == id) return option;
  }
  return null;
}

TaxonomyChoice? taxonomyChoice(List<TaxonomyChoice> options, String? id) =>
    taxonomyById(options, id, (option) => option.id);

TaxonomyCategory? taxonomyCategory(String? id) =>
    taxonomyById(projectTaxonomy, id, (category) => category.id);

TaxonomyGroup? taxonomyGroup(TaxonomyCategory? category, String? id) =>
    taxonomyById(category?.groups ?? const [], id, (group) => group.id);

TaxonomyProgram taxonomyProgram(TaxonomyGroup group, TaxonomyChoice type) =>
    projectPrograms[type.programId ?? group.programId]!;

