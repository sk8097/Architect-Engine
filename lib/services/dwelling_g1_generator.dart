/// One household, one rectangular common plate, a measured indoor stair and optional open terrace.
class DwellingG1Generator {
  static bool requested(ProjectBrief? brief) => brief?.requirements?.answers['cad_output'] == 'dwelling_g1';

  TowerResult generate(ProjectBrief brief, {required double widthFt, required double depthFt, required String facing}) {
    TowerResult stop(String message) => TowerResult(const [], [message]);
    final selection = brief.taxonomy, snapshot = brief.requirements;
    if (selection == null || snapshot == null || selection.version != projectTaxonomyVersion || snapshot.version != requirementsSchemaVersion) {
      return stop('Save this G+1 brief with the current measured requirements.');
    }
    if (selection.categoryId != 'residential' || selection.subcategoryId != 'houses' || !dwellingG1Types.contains(selection.typeId)) {
      return stop('Choose a supported individual house type for this G+1 layout.');
    }
    final a = snapshot.answers;
    if (brief.floorCount != 2 || (a['building_count'] as num? ?? 1) != 1 ||
        (a['basements'] as num? ?? 0) > 0 || (a['mezzanines'] as num? ?? 0) > 0) {
      return stop('This G+1 layout requires two floors for one building, without a basement or mezzanine.');
    }
    if (a['stair_access'] != 'inside' || a['stair_form'] != 'straight' || a['upper_use'] != 'private' || a['lift_plan'] != 'none') {
      return stop('This template supports an inside straight stair for one household, without a lift. External, shared and independent rental access are not generated.');
    }
    final wantsTerrace=a['terrace_needed']=='yes';
    if ((selection.actionId != null && !const {'new_design','concept_design','feasibility'}.contains(selection.actionId)) ||
        const {'existing','brownfield','partial_demolition'}.contains(a['build_status']) ||
        const {'existing','partial','renovation','demolish'}.contains(a['construction_status'])) {
      return stop('This is a new dwelling concept, not a surveyed alteration or approval drawing.');
    }
    if (!const {'rectangular','square'}.contains(selection.plotShapeId) || !const {'South','North','East','West'}.contains(facing)) {
      return stop('Use a measured rectangular or square plot and a cardinal frontage.');
    }
    if (a['house_form'] != null && !const {'duplex','g_plus_n'}.contains(a['house_form'])) return stop('The selected house form is not the supported two-level dwelling.');
    if (const {'with_rental_unit','split_level'}.contains(selection.configurationId)) return stop('Rental units or split levels are not generated by this house template.');
    int? mm(Object? value,{bool zero = false}) {
      if (value is! num || !value.isFinite || value < 0 || value > 300) return null;
      final n = (value * 1000).round();
      return n > 0 || zero ? n : null;
    }
    final plotW = mm(widthFt * .3048), plotD = mm(depthFt * .3048);
    final w = mm(a['cad_plate_width']), d = mm(a['cad_plate_depth']);
    final left = mm(a['cad_offset_left'],zero:true), front = mm(a['cad_offset_front'],zero:true);
    final wall = mm(a['cad_wall']), corridor = mm(a['cad_corridor']), door = mm(a['cad_door']);
    if (plotW == null || plotD == null || w == null || d == null || left == null || front == null || wall == null || corridor == null || door == null ||
        (selection.plotShapeId == 'square' && plotW != plotD)) return stop('Enter the measured plot, floor plate, offsets, wall, passage and door widths.');
    final right = plotW - left - w, rear = plotD - front - d;
    for (final (side,space) in [('left',left),('right',right),('front',front),('rear',rear)]) {
      final v = a['${side}_setback'];
      final inset = v == null ? 0 : mm(v, zero:true);
      if (inset == null || space < inset) return stop('The building conflicts with the plot boundary or $side setback.');
    }
    final coverage = a['coverage_limit'], fsi = a['fsi_limit'];
    if (coverage is num && w * d > plotW * plotD * coverage / 100) return stop('The footprint exceeds supplied coverage.');
    if (fsi is num && 2 * w * d > plotW * plotD * fsi) return stop('Both gross floor plates together exceed supplied FAR/FSI.');
    final rise = mm(a['g1_height']), stairW = mm(a['g1_width']), going = mm(a['g1_going']), landing = mm(a['g1_landing']);
    final risers = a['g1_risers'];
    if (rise == null || stairW == null || going == null || landing == null || risers is! int || risers < 2 || risers > 50) {
      return stop('Enter the measured rise, clear stair width, going, landing depth and 2 to 50 risers.');
    }
    final stair = StraightStairSpec(risers: risers, going: going, landing: landing, height: rise);
    StraightStairSpec? roofStair;
    int? roofWidth;
    if (wantsTerrace) {
      final uses=a['terrace_use'];
      if (uses is! Iterable || uses.length!=1 || uses.first!='open') {
        return stop('This terrace access template draws an open terrace only. Covered, enclosed and garden zones are not modelled.');
      }
      final height=mm(a['g1_roof_height']), roofGoing=mm(a['g1_roof_going']), roofLanding=mm(a['g1_roof_landing']);
      final steps=a['g1_roof_risers'];
      roofWidth=mm(a['g1_roof_stair_width']);
      if (height==null || roofGoing==null || roofLanding==null || roofWidth==null || steps is! int || steps<2 || steps>50) {
        return stop('Enter the second straight flight rise, clear width, going, landings and riser count for terrace access.');
      }
      roofStair=StraightStairSpec(risers:steps,going:roofGoing,landing:roofLanding,height:height);
    }
    final stairs=[TowerSpace('Straight stair',stairW,stair.depth),
      if (roofStair!=null) TowerSpace('Second terrace flight',roofWidth!,roofStair.depth)];
    final group = taxonomyGroup(taxonomyCategory(selection.categoryId),selection.subcategoryId)!;
    final type = taxonomyChoice(group.types,selection.typeId)!;
    final labels = {for (final option in taxonomyProgram(group,type).spaces) option.id: option.label,...snapshot.customSpaces};
    final requested = [<TowerSpace>[],<TowerSpace>[]];
    final ids = [<String>[],<String>[]];
    final levels = <String,int>{};
    final counts = selection.spaceQuantities;
    if (counts.values.fold(0,(sum,n)=>sum+n) > 2 * TowerPlanGenerator.maxSpaces || counts.values.any((c)=>c<1)) return stop('Use up to 24 measured rooms per floor.');
    for (final entry in counts.entries) {
      final id = entry.key, label = labels[entry.key];
      final detail = snapshot.spaceDetails[id] ?? const <String,Object>{};
      if (label == null || label.trim().isEmpty) return stop('An included room has no valid label.');
      if (const {'staircase','lift','terrace','garden','pool','balcony','outdoor_seating','verandah','attached_bathroom','open_kitchen'}.contains(id)) {
        return stop('$label is not a separate room in this template. Outdoor spaces, attached access and open kitchens need another layout. The measured stair is generated automatically.');
      }
      final raw = detail['floor_level'];
      if (raw != '0' && raw != '1') return stop('$label: assign Ground or First floor.');
      final level = raw == '0' ? 0 : 1;
      final width = mm(detail['width']), depth = mm(detail['length']), window = mm(detail['cad_window']);
      if (width == null || depth == null) return stop('$label: enter clear width and length.');
      if ((detail['cad_window'] != null || detail['daylight'] == 'required') && window == null) return stop('$label: enter a measured exterior window width.');
      levels[id] = level;
      for (var i=0;i<entry.value;i++) {
        requested[level].add(TowerSpace(entry.value == 1 ? label : '$label ${i+1}',width,depth,window:window));
        ids[level].add(id);
      }
    }
    final kitchenLevel = a['main_kitchen_floor'];
    if ((kitchenLevel != '0' && kitchenLevel != '1') || levels['closed_kitchen']?.toString() != kitchenLevel || levels['family_living_room']?.toString() != kitchenLevel ||
        counts['closed_kitchen'] != 1 || counts['family_living_room'] != 1 || (a['kitchen_type'] != null && a['kitchen_type'] != 'closed')) {
      return stop('Include one measured closed kitchen and one living room on the selected main-kitchen floor.');
    }
    if ((counts['shared_bathroom'] ?? 0) < 1 || (a['attached_toilets'] as num? ?? 0)>0 || (a['common_toilets'] != null && a['common_toilets'] != counts['shared_bathroom'])) {
      return stop('Include the requested shared bathrooms. Ensuite access is not part of this template.');
    }
    if (a['puja_needed'] == 'yes' && (a['puja_form'] != 'room' || levels['prayer_puja_room'] == null)) return stop('Include a measured separate puja room or use a different template for a niche or corner.');
    final inferred = int.tryParse(RegExp(r'^([1-5])_(?:bhk|bedroom)$').firstMatch(selection.configurationId ?? '')?.group(1) ?? '');
    final bedTotal = a['bedrooms'] ?? inferred;
    final allBeds = ids.expand((s)=>s).where(dwellingBedroomIds.contains).length;
    if (bedTotal is num && allBeds != bedTotal) return stop('Measured bedroom quantities do not match the requested bedroom count.');
    for (var i=0;i<2;i++) {
      final beds = ids[i].where(dwellingBedroomIds.contains).length;
      final baths = ids[i].where((id)=>id=='shared_bathroom').length;
      if (a['level_bedrooms_$i'] != beds || a['level_baths_$i'] != baths) {
        return stop('${i == 0 ? 'Ground' : 'First'} floor rooms do not match the saved bedroom and bathroom counts.');
      }
    }
    for (final id in levels.keys) {
      final required = snapshot.spaceDetails[id]?['adjacent_required'];
      if (required is Iterable && required.any((other)=>other == id || levels[other] != levels[id])) {
        return stop('${labels[id]} needs a required adjacent room on the same floor.');
      }
    }
    final rotated = facing=='East'||facing=='West';
    final x = switch (facing) {'North'=>right,'East'=>rear,'West'=>front,_=>left};
    final y = switch (facing) {'North'=>rear,'East'=>left,'West'=>right,_=>front};
    final shell = TowerBrief(floors:2,plotWidth:rotated?plotD:plotW,plotDepth:rotated?plotW:plotD,
      plateWidth:rotated?d:w,plateDepth:rotated?w:d,westOffset:x,southOffset:y,frontage:facing,
      wall:wall,corridor:corridor,door:door,basis:'Measured dwelling brief',stairs:stairs,lifts:const [],shafts:const [],
      groups:[for (var level=0;level<2;level++) TowerFloorGroup('${type.label} G+1',level+1,level+1,requested[level])]);
    final result = TowerPlanGenerator().generateDwelling(shell,stair,roofStair:roofStair);
    if (result.sheets.isEmpty) return result;
    bool adjoining(PlanRect a,PlanRect b) => ((a.left==b.right+wall||b.left==a.right+wall)&&a.bottom<b.top&&b.bottom<a.top)||
      ((a.bottom==b.top+wall||b.bottom==a.top+wall)&&a.left<b.right&&b.left<a.right);
    for (var level=0;level<2;level++) {
      final sheet = result.sheets[level];
      final roomMap = {for (var i=0;i<ids[level].length;i++) 'room_$i':ids[level][i]};
      final rooms = sheet.plan.rooms.where((r)=>roomMap.containsKey(r.id));
      for (final room in rooms) {
        final id = roomMap[room.id], detail = snapshot.spaceDetails[roomMap[room.id]] ?? const <String,Object>{};
        final req = detail['adjacent_required'], sep = detail['separate_from'];
        if ((req is Iterable && req.any((other)=>!rooms.any((r)=>roomMap[r.id]==other&&adjoining(r.bounds,room.bounds)))) ||
            (sep is Iterable && rooms.any((r)=>sep.contains(roomMap[r.id])&&adjoining(r.bounds,room.bounds)))) {
          return stop('${sheet.range}: this arrangement does not satisfy the required room relationship for ${labels[id]}.');
        }
        final p = sheet.plan.footprint, b = room.bounds;
        final (frontGap,rearGap,leftGap,rightGap) = switch(facing) {
          'North'=>(p.top-b.top,b.bottom-p.bottom,p.right-b.right,b.left-p.left),
          'East'=>(p.right-b.right,b.left-p.left,b.bottom-p.bottom,p.top-b.top),
          'West'=>(b.left-p.left,p.right-b.right,p.top-b.top,b.bottom-p.bottom),
          _=>(b.bottom-p.bottom,p.top-b.top,b.left-p.left,p.right-b.right),
        };
        if (!(switch(detail['zone_edge']){'front'=>frontGap==wall,'rear'=>rearGap==wall,'left'=>leftGap==wall,'right'=>rightGap==wall,_=>true})) {
          return stop('${sheet.range}: ${labels[id]} does not reach its required outside edge.');
        }
        for (final key in ['area_min','area_max']) {
          final area = detail[key];
          if (area is! num) continue;
          final unit = detail['area_unit'];
          if (unit != 'sqm' && unit != 'sqft') return stop('${labels[id]}: supply an area unit.');
          final target = area * (unit == 'sqft' ? .09290304 : 1);
          if (key == 'area_min' ? b.area/1000000 < target-.001 : b.area/1000000 > target+.001) {
            return stop('${labels[id]}: measured dimensions conflict with the requested area limit.');
          }
        }
      }
    }
    final ground = result.sheets.first;
    final parking = dwellingSurfaceParking(ground.plan, brief.parking, a);
    if (parking.issue case final issue?) return stop(issue);
    TowerSheet? roof;
    if (roofStair!=null) {
      final walk=mm(a['g1_roof_walk']), width=mm(a['g1_roof_width']), length=mm(a['g1_roof_depth']), parapet=mm(a['g1_roof_parapet']);
      final allowance=a['terrace_sqft'], target=a['terrace_area_open'];
      if (walk==null || width==null || length==null || parapet==null || allowance is! num || !allowance.isFinite || allowance<=0 || target is! num || !target.isFinite || target<=0) {
        return stop('Enter a measured terrace walk, open deck and parapet, plus both available and requested terrace areas.');
      }
      final plan=dwellingRoofTerrace(result.sheets[1],roofStair,wall:wall,door:door,parapet:parapet,walkWidth:walk,
        deckWidth:width,deckDepth:length,areaLimitSqft:allowance.toDouble(),targetSqft:target.toDouble());
      if (plan.issue != null) return stop(plan.issue!);
      if (fsi is num && 2*w*d+plan.headArea>plotW*plotD*fsi) {
        return stop('Both floor plates plus the roof stair enclosure exceed the supplied FAR/FSI allowance when counted together.');
      }
      roof=plan.sheet;
    }
    if (parking.zones.isEmpty && roof==null) return result;
    return TowerResult(List.unmodifiable([
      if (parking.zones.isEmpty) ground else
        TowerSheet(ground.name,ground.range,ground.first,ground.last,ground.plan,ground.unallocated,siteZones:parking.zones),
      ...result.sheets.skip(1),if (roof!=null) roof,
    ]),const []);
  }
}
